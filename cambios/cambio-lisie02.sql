-- Catalogo de modelos: cada version entrenada debe tener su propio registro.
CREATE TABLE IF NOT EXISTS warehouse.modelo_ia (
    id_modelo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    version VARCHAR(50) NOT NULL,
    fecha_entrenamiento TIMESTAMPTZ,
    metricas_evaluacion JSONB NOT NULL DEFAULT '{}'::jsonb,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_modelo_ia_nombre_version UNIQUE (nombre, version),
    CONSTRAINT uq_modelo_ia_id_version UNIQUE (id_modelo, version),
    CONSTRAINT chk_modelo_ia_metricas_objeto CHECK (jsonb_typeof(metricas_evaluacion) = 'object')
);

-- Resultado de inferencia. El FK compuesto apunta a un hecho de grano obra-mes.
CREATE TABLE IF NOT EXISTS warehouse.prediccion_riesgo (
    id_prediccion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tiempo_key INTEGER NOT NULL,
    obra_key BIGINT NOT NULL,
    id_modelo BIGINT NOT NULL,
    version_modelo VARCHAR(50) NOT NULL,
    fecha_generacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    probabilidad_retraso NUMERIC(5,4) NOT NULL,
    nivel_riesgo VARCHAR(10) NOT NULL,
    dias_retraso_estimados INTEGER,
    factores_relevantes JSONB NOT NULL DEFAULT '[]'::jsonb,
    CONSTRAINT chk_prediccion_probabilidad CHECK (probabilidad_retraso BETWEEN 0 AND 1),
    CONSTRAINT chk_prediccion_nivel CHECK (nivel_riesgo IN ('BAJO', 'MEDIO', 'ALTO')),
    CONSTRAINT chk_prediccion_dias CHECK (dias_retraso_estimados IS NULL OR dias_retraso_estimados >= 0),
    CONSTRAINT chk_prediccion_factores_json CHECK (jsonb_typeof(factores_relevantes) IN ('array', 'object')),
    CONSTRAINT fk_prediccion_hecho_mensual
        FOREIGN KEY (tiempo_key, obra_key)
        REFERENCES warehouse.fact_obra_mensual (tiempo_key, obra_key)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_prediccion_modelo_version
        FOREIGN KEY (id_modelo, version_modelo)
        REFERENCES warehouse.modelo_ia (id_modelo, version)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_prediccion_riesgo_obra_periodo
    ON warehouse.prediccion_riesgo (obra_key, tiempo_key, fecha_generacion DESC);
CREATE INDEX IF NOT EXISTS idx_prediccion_riesgo_modelo
    ON warehouse.prediccion_riesgo (id_modelo, version_modelo);

COMMENT ON TABLE warehouse.modelo_ia IS
    'Catalogo de modelos de IA y sus versiones, fecha de entrenamiento y metricas de evaluacion.';
COMMENT ON TABLE warehouse.prediccion_riesgo IS
    'Historial de probabilidades de retraso predichas por version de modelo para un hecho mensual especifico.';
COMMENT ON COLUMN warehouse.prediccion_riesgo.version_modelo IS
    'Copia de la version usada en la inferencia; una FK compuesta garantiza que coincida con el modelo relacionado.';
COMMENT ON COLUMN warehouse.prediccion_riesgo.probabilidad_retraso IS
    'Probabilidad entre 0 y 1; NUMERIC(5,4) evita errores de redondeo binario y admite cuatro decimales.';
COMMENT ON COLUMN warehouse.prediccion_riesgo.factores_relevantes IS
    'Lista u objeto JSON con factores explicativos producidos por la inferencia.';

COMMIT;
