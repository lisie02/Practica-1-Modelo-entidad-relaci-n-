CREATE TABLE categoria (
    id_categoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT
);

CREATE TABLE pais (
    id_pais INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE material (
    id_material INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    tipo VARCHAR(100),
    reciclable BOOLEAN
);

CREATE TABLE fuente (
    id_fuente INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    tipo VARCHAR(100),
    url VARCHAR(255),
    fecha_consulta DATE
);

CREATE TABLE producto (
    id_producto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    marca VARCHAR(100),
    precio_aproximado DECIMAL(10,2),
    vida_util VARCHAR(100),
    id_categoria INT NOT NULL,
    id_pais INTEGER,
    FOREIGN KEY (id_categoria)
        REFERENCES categoria(id_categoria),
    FOREIGN KEY (id_pais)
        REFERENCES pais(id_pais)
);

CREATE TABLE producto_reutilizable (
    id_producto INT PRIMARY KEY,
    numero_reutilizaciones INT,
    requiere_mantenimiento BOOLEAN,
    FOREIGN KEY (id_producto)
        REFERENCES producto(id_producto)
);

CREATE TABLE producto_desechable (
    id_producto INT PRIMARY KEY,
    tiempo_descomposicion_anios INT,
    genera_residuos BOOLEAN,
    FOREIGN KEY (id_producto)
        REFERENCES producto(id_producto)
);

CREATE TABLE producto_material (
    id_producto INT NOT NULL,
    id_material INT NOT NULL,
    PRIMARY KEY (id_producto, id_material),
    FOREIGN KEY (id_producto)
        REFERENCES producto(id_producto),
    FOREIGN KEY (id_material)
        REFERENCES material(id_material)
);

CREATE TABLE impacto_ambiental (
    id_impacto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto INT NOT NULL,
    id_fuente INT NOT NULL,
    consumo_agua DECIMAL(12,2),
    consumo_energia DECIMAL(12,2),
    emisiones_co2 DECIMAL(12,6),
    residuos_generados DECIMAL(12,2),
    nivel_impacto VARCHAR(50),
    fecha_dato DATE,
    FOREIGN KEY (id_producto)
        REFERENCES producto(id_producto),
    FOREIGN KEY (id_fuente)
        REFERENCES fuente(id_fuente)
);
-- Restricción de disyunción de la jerarquía ISA:
-- un producto no puede ser reutilizable y desechable al mismo tiempo.

CREATE OR REPLACE FUNCTION verificar_disyuncion_producto()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_TABLE_NAME = 'producto_reutilizable' THEN
        IF EXISTS (
            SELECT 1
            FROM producto_desechable
            WHERE id_producto = NEW.id_producto
        ) THEN
            RAISE EXCEPTION
                'El producto % ya está registrado como desechable',
                NEW.id_producto;
        END IF;
    ELSE
        IF EXISTS (
            SELECT 1
            FROM producto_reutilizable
            WHERE id_producto = NEW.id_producto
        ) THEN
            RAISE EXCEPTION
                'El producto % ya está registrado como reutilizable',
                NEW.id_producto;
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_disyuncion_reutilizable
BEFORE INSERT OR UPDATE OF id_producto
ON producto_reutilizable
FOR EACH ROW
EXECUTE FUNCTION verificar_disyuncion_producto();

CREATE TRIGGER trg_disyuncion_desechable
BEFORE INSERT OR UPDATE OF id_producto
ON producto_desechable
FOR EACH ROW
EXECUTE FUNCTION verificar_disyuncion_producto();
